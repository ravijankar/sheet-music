#!/usr/bin/env python3
"""Add an Eb alto saxophone staff to a concert-pitch lead sheet (.mscx).

Usage: add-alto-part.py input.mscx output.mscx

The alto staff is a copy of staff 1 (melody + chord symbols) on a transposing
instrument, so MuseScore shows it a major sixth up. The melody drops an octave
when that keeps it inside the horn's range and off the ledger lines.
Scores that already have an alto sax are left alone (exit code 2).
"""
import copy
import re
import sys
import xml.etree.ElementTree as ET

TPC_SHIFT = 3            # concert -> Eb alto on the line of fifths (C -> A)
WRITTEN_SHIFT = 9        # semitones from sounding to written pitch
LOWEST_WRITTEN = 58      # Bb3
HIGHEST_COMFORTABLE = 85  # C#6

# System-wide elements that live on the top staff only.
SYSTEM_ELEMENTS = {"Clef", "Tempo", "RehearsalMark", "SystemText", "Marker",
                   "Jump", "Segment", "LayoutBreak"}
# Regenerated by MuseScore for the transposed staff.
STALE_ELEMENTS = {"eid", "StemDirection", "Accidental"}

ALTO_PART = """
<Part id="{id}">
  <Staff>
    <StaffType group="pitched">
      <name>stdNormal</name>
    </StaffType>
  </Staff>
  <trackName>Alto Saxophone</trackName>
  <Instrument id="alto-saxophone">
    <longName>Alto Saxophone</longName>
    <shortName>A. Sax.</shortName>
    <trackName>Alto Saxophone</trackName>
    <minPitchP>49</minPitchP>
    <maxPitchP>92</maxPitchP>
    <minPitchA>49</minPitchA>
    <maxPitchA>80</maxPitchA>
    <transposeDiatonic>-5</transposeDiatonic>
    <transposeChromatic>-9</transposeChromatic>
    <instrumentId>wind.reed.saxophone.alto</instrumentId>
    <Channel>
      <program value="65"/>
      <synti>Fluid</synti>
    </Channel>
    <Channel name="harmony">
      <program value="0"/>
      <synti>Fluid</synti>
    </Channel>
  </Instrument>
</Part>
"""


NOTE_TPC = {"F": 13, "C": 14, "G": 15, "D": 16, "A": 17, "E": 18, "B": 19}
TPC_NOTE = {v: k for k, v in NOTE_TPC.items()}


def transpose_note_names(text):
    """Transpose note names typed into a chord suffix, e.g. the G in "7G6"."""
    def shift(m):
        alter = {"": 0, "b": -1, "♭": -1, "#": 1, "♯": 1}[m.group(2)]
        tpc = NOTE_TPC[m.group(1)] + 7 * alter + TPC_SHIFT
        step = (tpc - 13) % 7 + 13
        accidental = {-1: "♭", 0: "", 1: "♯"}.get((tpc - step) // 7)
        return m.group(0) if accidental is None else TPC_NOTE[step] + accidental
    return re.sub(r"([A-G])([b♭#♯]?)", shift, text)


def insert_after(parent, anchor_tag, new):
    anchor = parent.find(anchor_tag)
    parent.insert(list(parent).index(anchor) + 1, new)


def strip(elem):
    for child in list(elem):
        if (child.tag in STALE_ELEMENTS or child.tag in SYSTEM_ELEMENTS
                or (child.tag == "Spanner" and child.get("type") == "Volta")):
            elem.remove(child)
        else:
            strip(child)


def transpose(measure, octave_drop):
    for child in list(measure):
        if child.tag != "voice":
            measure.remove(child)
    strip(measure)
    for note in measure.iter("Note"):
        if octave_drop:
            pitch = note.find("pitch")
            pitch.text = str(int(pitch.text) - 12)
        tpc2 = ET.Element("tpc2")
        tpc2.text = str(int(note.find("tpc").text) + TPC_SHIFT)
        insert_after(note, "tpc", tpc2)
    for harmony in measure.iter("Harmony"):
        for tag in ("root", "bass"):
            for e in harmony.iter(tag):
                e.text = str(int(e.text) + TPC_SHIFT)
        for name in harmony.iter("name"):
            name.text = transpose_note_names(name.text or "")
    for keysig in measure.iter("KeySig"):
        concert = keysig.find("concertKey")
        if concert is not None:
            actual = ET.Element("actualKey")
            actual.text = str(int(concert.text) + TPC_SHIFT)
            insert_after(keysig, "concertKey", actual)


def main(src, dst):
    tree = ET.parse(src)
    score = tree.getroot().find("Score")
    parts = score.findall("Part")
    if any("saxophone.alto" in (i.text or "") for i in score.iter("instrumentId")):
        print(f"already has an alto sax: {src}")
        return 2

    staves = score.findall("Staff")
    lead = staves[0]
    pitches = [int(p.text) + WRITTEN_SHIFT for p in lead.iter("pitch")]
    octave_drop = (max(pitches) > HIGHEST_COMFORTABLE
                   and min(pitches) - 12 >= LOWEST_WRITTEN)

    part = ET.fromstring(ALTO_PART.format(id=len(parts) + 1))
    score.insert(list(score).index(parts[-1]) + 1, part)

    alto = ET.Element("Staff", id=str(len(staves) + 1))
    for measure in lead.findall("Measure"):
        m = copy.deepcopy(measure)
        transpose(m, octave_drop)
        alto.append(m)

    # A lead sheet in C may carry no key signature at all; the alto still needs A major.
    first_voice = alto.find("Measure/voice")
    if first_voice.find("KeySig") is None:
        keysig = ET.Element("KeySig")
        ET.SubElement(keysig, "concertKey").text = "0"
        ET.SubElement(keysig, "actualKey").text = str(TPC_SHIFT)
        first_voice.insert(0, keysig)

    score.insert(list(score).index(staves[-1]) + 1, alto)
    tree.write(dst, encoding="UTF-8", xml_declaration=True)
    lo, hi = min(pitches), max(pitches)
    if octave_drop:
        lo, hi = lo - 12, hi - 12
    print(f"written range {lo}-{hi}{' (octave down)' if octave_drop else ''}: {dst}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1], sys.argv[2]))
